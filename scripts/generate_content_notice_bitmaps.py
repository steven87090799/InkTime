"""Bake the three fixed Traditional Chinese footer labels into firmware.

Uses the project's OFL Iansui font; no font engine, network or dynamic text is
needed on the frame. Run from any directory with the project's Pillow runtime.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT = 640, 28
LABELS = (
    ("EmptyLibrary", "照片庫沒有照片，請加入照片"),
    ("AnalysisRequired", "照片尚未完成必要分析，暫停換圖"),
    ("NoEligiblePhotos", "暫無符合條件的照片，保留目前畫面"),
)


def main() -> None:
    font = ImageFont.truetype(
        str(ROOT / "inktime/app/domain/rendering/font_assets/Iansui-Regular.ttf"), 24,
    )
    lines = [
        "// Generated by scripts/generate_content_notice_bitmaps.py; do not edit.",
        "// Glyphs: Iansui-Regular.ttf (SIL OFL, project font_assets/Iansui-OFL.txt).",
        "#pragma once", "#include <stdint.h>", "namespace inktime {",
        f"constexpr uint16_t kContentNoticeTextWidth = {WIDTH};",
        f"constexpr uint16_t kContentNoticeTextHeight = {HEIGHT};",
    ]
    for name, text in LABELS:
        mask = Image.new("1", (WIDTH, HEIGHT), 1)
        ImageDraw.Draw(mask).text((WIDTH // 2, HEIGHT // 2), text, font=font, fill=0, anchor="mm")
        data = bytes(value ^ 0xFF for value in mask.tobytes())
        lines.append(f"// {text}")
        lines.append(f"constexpr uint8_t kContentNotice{name}[] = {{")
        lines.extend(
            "  " + ",".join(f"0x{value:02x}" for value in data[start:start + 24]) + ","
            for start in range(0, len(data), 24)
        )
        lines.append("};")
    lines.append("}  // namespace inktime")
    (ROOT / "esp32/ink-display-7C-photo/content_notice_bitmaps.h").write_text(
        "\n".join(lines) + "\n", encoding="utf-8",
    )


if __name__ == "__main__":
    main()
